/** Number columns on the country tabs (USA, UK, DE+FR+IT+ES, Canada). */
export const NUMERIC_FIELDS = [
  "amazon",
  "externalWarehouse",
  "receiving",
  "otw1",
  "otw2",
  "last30",
  "sending",
  "futureOrder",
] as const;

export type NumericField = (typeof NUMERIC_FIELDS)[number];

/** Columns on the Supplier Inventory tab that are typed in. */
/** packSize = single units the supplier makes per Amazon ASIN (2 for a 2 Pack doorstopper). */
export const SUPPLIER_NUMBER_FIELDS = ["ready", "underProduction", "packSize"] as const;
export const SUPPLIER_TEXT_FIELDS = ["supplierName", "supplierLink"] as const;
export type SupplierNumberField = (typeof SUPPLIER_NUMBER_FIELDS)[number];
export type SupplierTextField = (typeof SUPPLIER_TEXT_FIELDS)[number];
export type SupplierField = SupplierNumberField | SupplierTextField;

/** Where each column is filled from automatically. Anything can still be overwritten by hand. */
export function autoSource(country: string, field: NumericField): string | null {
  if (field === "amazon") return "Amazon MCP · FBA available + FC processing";
  if (field === "last30") return "Amazon MCP · units ordered";
  if (field === "externalWarehouse" && country === "US") return "Amazon MCP · AWD available";
  if (field === "otw1" || field === "otw2") return "Proboxx MCP";
  return null;
}

export type CellSource = "sheet" | "amazon" | "proboxx" | "manual" | "api";
export type CellMeta = { source: CellSource; at: string };

export interface Child {
  id: string;
  name: string;
  asin: string | null;
  sourceRow?: number;
  amazon: number | null;
  externalWarehouse: number | null;
  receiving: number | null;
  otw1: number | null;
  otw2: number | null;
  last30: number | null;
  /** Sending Inventory — typed in. Subtracted from the supplier's stock on the Supplier tab. */
  sending: number | null;
  /** Future order — typed in. Summed over all marketplaces on the Supplier tab. */
  futureOrder: number | null;
  /** Where each value last came from and when. */
  meta?: Partial<Record<NumericField, CellMeta>>;
}

export interface Group {
  id: string;
  name: string;
  sourceRow?: number;
  children: Child[];
}

export interface ColumnLabels {
  items: string;
  asin: string;
  amazon: string;
  externalWarehouse: string;
  receiving: string;
  otw1: string;
  otw2: string;
  last30: string;
  monthsAmazon: string;
  monthsTotal: string;
}

export interface SyncState {
  lastSyncedAt?: string;
  status?: "ok" | "partial" | "error";
  message?: string;
  /** Business Report ids (per marketplace) still being generated by Amazon; the next sync collects them. */
  pendingReports?: Record<string, string>;
}

export interface Country {
  id: "US" | "UK" | "EU" | "CA";
  label: string;
  marketplaceIds: string[];
  columnLabels: ColumnLabels;
  groups: Group[];
  sync?: SyncState;
}

export interface SupplierItem {
  id: string;
  name: string;
  asin: string | null;
  ready: number | null;
  underProduction: number | null;
  /** Units per pack: Sending Inventory and Future order (Amazon packs) are multiplied by this
   *  to get the single units the supplier produces. 1 for products made as packs. */
  packSize?: number | null;
  supplierName: string | null;
  supplierLink: string | null;
  meta?: Partial<Record<SupplierField, CellMeta>>;
}

export interface SupplierGroup {
  id: string;
  name: string;
  children: SupplierItem[];
}

export interface InventoryDoc {
  source: string;
  sheetLastUpdated: string | null;
  importedAt: string;
  updatedAt?: string;
  countries: Country[];
  supplier: { groups: SupplierGroup[] };
}

/** One cell edit. `country: "SUPPLIER"` targets the Supplier Inventory tab. */
export type CellUpdate =
  | { country: Country["id"]; id?: string; asin?: string; field: NumericField; value: number | null }
  | { country: "SUPPLIER"; id?: string; asin?: string; field: SupplierNumberField; value: number | null }
  | { country: "SUPPLIER"; id?: string; asin?: string; field: SupplierTextField; value: string | null };
