export const NUMERIC_FIELDS = [
  "amazon",
  "externalWarehouse",
  "receiving",
  "otw1",
  "otw2",
  "last30",
] as const;

export type NumericField = (typeof NUMERIC_FIELDS)[number];

/** Where each column is filled from automatically. Anything can still be overwritten by hand. */
export function autoSource(country: string, field: NumericField): string | null {
  if (field === "amazon") return "SP-API · FBA available + FC processing";
  if (field === "last30") return "SP-API · Business Reports";
  if (field === "externalWarehouse" && country === "US") return "SP-API · AWD available";
  if (field === "otw1" || field === "otw2") return "Proboxx API";
  return null;
}

export type CellSource = "sheet" | "amazon" | "proboxx" | "manual" | "api";

export interface Child {
  id: string;
  name: string;
  asin: string | null;
  sourceRow?: number;
  amazon: number | null;
  externalWarehouse: number | null;
  receiving: number | null;
  otw1: number | null;
  otw2: number | null;
  last30: number | null;
  /** Where each value last came from and when. */
  meta?: Partial<Record<NumericField, { source: CellSource; at: string }>>;
}

export interface Group {
  id: string;
  name: string;
  sourceRow?: number;
  children: Child[];
}

export interface ColumnLabels {
  items: string;
  asin: string;
  amazon: string;
  externalWarehouse: string;
  receiving: string;
  otw1: string;
  otw2: string;
  last30: string;
  monthsAmazon: string;
  monthsTotal: string;
}

export interface SyncState {
  lastSyncedAt?: string;
  status?: "ok" | "partial" | "error";
  message?: string;
  /** Business Report ids (per marketplace) still being generated by Amazon; the next sync collects them. */
  pendingReports?: Record<string, string>;
}

export interface Country {
  id: "US" | "UK" | "EU" | "CA";
  label: string;
  marketplaceIds: string[];
  columnLabels: ColumnLabels;
  groups: Group[];
  sync?: SyncState;
}

export interface InventoryDoc {
  source: string;
  sheetLastUpdated: string | null;
  importedAt: string;
  updatedAt?: string;
  countries: Country[];
}

export interface CellUpdate {
  country: Country["id"];
  /** Either the row id or the ASIN identifies the row. */
  id?: string;
  asin?: string;
  field: NumericField;
  value: number | null;
}
